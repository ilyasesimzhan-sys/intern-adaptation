// Метка для строк интерфейса, объявленных вне компонентов (константы модулей): сама ничего не делает,
// а перевод выполняется при отрисовке через t(). По этой метке scripts/check-i18n.mjs находит строки для словаря.
export const msg = (text) => text

// Подстановка параметров {name} в строку.
export function fill(text, params) {
  if (!params) return text
  return text.replace(/\{(\w+)\}/g, (m, key) => (key in params ? String(params[key]) : m))
}

// «Перевод» на русский — исходный язык: только подставляет параметры. Используется по умолчанию там,
// где текст сохраняется в базу (например, подписи журнала) и должен остаться русским.
export const ru = (text, params) => fill(text, params)
